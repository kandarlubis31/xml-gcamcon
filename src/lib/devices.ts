export function getDevice(codename: string): Device | undefined {
  return devices.find((d) => d.codename === codename);
}

export function getSensorName(device: Device, cameraId: number): string {
  const sensor = device.sensors.find((s) => s.id === cameraId);
  return sensor
    ? `${sensor.name} (${sensor.megapixels}MP ${sensor.aperture})`
    : `Camera ${cameraId}`;
}
